print("== 6. Type I: symmetry stabilizer does not classify hulls ==")
# M_2 with tracial state, SO(3) acting by the adjoint action; O(2)_z and SO(3) both have trivial fixed algebra
def fixed_algebra_of_unitaries(Us, n):
    def L(Xm):
        return sum(U.conj().T @ Xm @ U - Xm for U in Us)
    return fixed_space(L, n)


Uz = expm(-1j * 0.731 * Z / 2)  # irrational angle generates SO(2)_z densely
