print("== 7. Foreground selection: Davis-Kahan alignment of the top-k eigenspace ==")
rng2 = np.random.default_rng(7)
worst = 0.0
for trial in range(200):
    Dn = 8; k = 3
    w_diag = np.sort(rng2.uniform(0, 1, Dn))[::-1]
    gap = w_diag[k - 1] - w_diag[k]
    Eoff = rng2.normal(size=(Dn, Dn)) * 0.02; Eoff = (Eoff + Eoff.T) / 2; np.fill_diagonal(Eoff, 0)
    W = np.diag(w_diag) + Eoff
    lam, V = eigh(W)
    Vk = V[:, np.argsort(lam)[::-1][:k]]
    Pk = Vk @ Vk.T
    Pptr = np.diag([1.0] * k + [0.0] * (Dn - k))
    sin_theta = norm(Pk - Pptr, 2)
    bound = norm(Eoff, 2) / max(gap - norm(Eoff, 2), 1e-12)
    if gap > 2 * norm(Eoff, 2):
        worst = max(worst, sin_theta / bound)
allok &= report("sin(theta) <= ||E_off|| / (gap - ||E_off||) in all trials with gap > 2||E_off||", worst <= 1.0 + 1e-9)
print("  worst ratio sin(theta)/bound =", round(worst, 4))

