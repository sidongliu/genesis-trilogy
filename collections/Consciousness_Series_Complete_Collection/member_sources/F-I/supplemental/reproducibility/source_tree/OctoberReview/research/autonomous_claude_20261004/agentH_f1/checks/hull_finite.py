print("== 3. Stationarity theorem on a structured Lindbladian (C^2 (x) C^3) ==")
rng = np.random.default_rng(20261006)
# ergodic noise on the second factor: random Lindblad operators on C^3
d2 = 3
Ls = [rng.normal(size=(d2, d2)) + 1j * rng.normal(size=(d2, d2)) for _ in range(2)]
Hn = rng.normal(size=(d2, d2)) + 1j * rng.normal(size=(d2, d2)); Hn = Hn + Hn.conj().T


def Lstar_factor(Xf):
    out = 1j * (Hn @ Xf - Xf @ Hn)
    for Lk in Ls:
        out += Lk.conj().T @ Xf @ Lk - 0.5 * (Lk.conj().T @ Lk @ Xf + Xf @ Lk.conj().T @ Lk)
    return out


def Lstar3(Xfull):
    # act as id (x) Lstar_factor on M_2 (x) M_3
    Xr = Xfull.reshape(2, d2, 2, d2)
    out = np.zeros_like(Xr)
    for a in range(2):
        for b in range(2):
            out[a, :, b, :] = Lstar_factor(Xr[a, :, b, :])
    return out.reshape(2 * d2, 2 * d2)


def Lschr_factor(r):
    out = -1j * (Hn @ r - r @ Hn)
    for Lk in Ls:
        out += Lk @ r @ Lk.conj().T - 0.5 * (Lk.conj().T @ Lk @ r + r @ Lk.conj().T @ Lk)
    return out


# stationary state tau of the factor dynamics
E = [np.zeros((d2, d2), complex) for _ in range(d2 * d2)]
for k in range(d2 * d2):
    E[k].reshape(-1)[k] = 1
A = np.array([Lschr_factor(e).reshape(-1) for e in E]).T
w, v = np.linalg.eig(A)
tau = v[:, np.argmin(abs(w))].reshape(d2, d2); tau = tau / np.trace(tau); tau = (tau + tau.conj().T) / 2
print("  min eigenvalue of tau (faithful):", round(min(eigh(tau)[0]).real, 6))
F3 = fixed_space(Lstar3, 2 * d2)
allok &= report("Fix(E) = M_2 (x) 1 (dim 4) and a *-algebra", len(F3) == 4 and is_star_algebra(F3))
r1 = np.array([[0.6, 0.1 + 0.05j], [0.1 - 0.05j, 0.4]])
omega_prod = np.kron(r1, tau)
allok &= report("stationary product state: Fix(E) is modular-invariant (MOD holds)",
                modular_invariant(F3, omega_prod))
# omega-preserving expectation onto Fix and persistence E_fix o E_t = E_fix
Pfix = omega_expectation(F3, omega_prod)
Xr = rng.normal(size=(6, 6)) + 1j * rng.normal(size=(6, 6))

def evolve_heis(Xm, t, steps=400):
    # integrate dX/dt = Lstar3(X) with RK4
    h = t / steps
    Y_ = Xm.copy()
    for _ in range(steps):
        k1 = Lstar3(Y_); k2 = Lstar3(Y_ + h / 2 * k1); k3 = Lstar3(Y_ + h / 2 * k2); k4 = Lstar3(Y_ + h * k3)
        Y_ = Y_ + h / 6 * (k1 + 2 * k2 + 2 * k3 + k4)
    return Y_


Xt = evolve_heis(Xr, 0.7)
allok &= report("E_fix o E_t = E_fix (persistent projection, no back-flow)", norm(Pfix(Xt) - Pfix(Xr)) < 1e-8)
f1, f2 = F3[1], F3[2]
allok &= report("E_fix is Fix-bimodular", norm(Pfix(f1 @ Xr @ f2) - f1 @ Pfix(Xr) @ f2) < 1e-8)
allok &= report("omega o E_fix = omega", abs(np.trace(omega_prod @ Pfix(Xr)) - np.trace(omega_prod @ Xr)) < 1e-10)
# non-stationary entangled faithful state: MOD fails
psi = np.zeros(6, complex); psi[0] = 1 / np.sqrt(2); psi[4] = 1 / np.sqrt(2)  # |0>|0> + |1>|1>
omega_ent = 0.7 * np.outer(psi, psi.conj()) + 0.3 * np.eye(6) / 6
ent_r = omega_ent.reshape(2, d2, 2, d2)
ent_dot = np.zeros_like(ent_r)
for a in range(2):
    for b in range(2):
        ent_dot[a, :, b, :] = Lschr_factor(ent_r[a, :, b, :])
allok &= report("non-stationary entangled state: Fix(E) not modular-invariant (MOD fails)",
                norm(ent_dot) > 1e-6 and not modular_invariant(F3, omega_ent))

print("== 4. HAFF-B collective coupling on three qubits; stationary block-diagonal Gibbs-type state ==")
Xs = [kron(X, I2, I2), kron(I2, X, I2), kron(I2, I2, X)]
Zs = [kron(Z, I2, I2), kron(I2, Z, I2), kron(I2, I2, Z)]
Mcol = sum(Xs)
L4 = dephasing([(Mcol, 1.0)])
F4 = fixed_space(L4, 8)
# block projections of M (eigenvalues 3,1,-1,-3): the record (centre) algebra
evals, evecs = eigh(Mcol)
blocks = {}
for val, vec in zip(np.round(evals, 8), evecs.T):
    blocks.setdefault(val, []).append(vec)
Pblocks = [sum(np.outer(v, v.conj()) for v in vs) for vs in blocks.values()]
print("  block dims:", [int(round(np.trace(P).real)) for P in Pblocks], " dim Fix =", len(F4))
# a stationary faithful state: Gibbs state of a Hamiltonian commuting with M (inside Fix)
Hh = 0.8 * (Zs[0] @ Zs[1] + Zs[1] @ Zs[2] + Zs[0] @ Zs[2])  # not commuting with M in general
Hin = sum(P @ Hh @ P for P in Pblocks)  # block-diagonal part, commutes with M
rho4 = expm(-0.9 * Hin); rho4 /= np.trace(rho4)
allok &= report("rho4 stationary under the collective dephasing", norm(L4(rho4)) < 1e-10)
Hrec = hull(Pblocks, rho4, L4)
allok &= report("records alone: hull(block projections) = their span (dim 4, abelian)",
                len(Hrec) == len(Pblocks) == 4 and is_star_algebra(Hrec))
# an in-block seed: X1 - X2 commutes with M and acts inside the blocks (lies in Fix)
seed_in = Xs[0] - Xs[1]  # commutes with M, nonscalar inside the 3-dim blocks
allok &= report("in-block seed lies in Fix(E)", contains(F4, seed_in))
Hin_hull = hull([seed_in], rho4, L4)
Wseed = wstar([seed_in], 8)
Wseed_rho = wstar([seed_in, rho4], 8)
print("  dim W*(S) =", len(Wseed), " dim hull =", len(Hin_hull), " dim W*(S,rho) =", len(Wseed_rho), " dim Fix =", len(F4))
allok &= report("sandwich W*(S) <= hull(S) <= W*(S, rho) and hull <= Fix",
                subspace_in(Wseed, Hin_hull) and subspace_in(Hin_hull, Wseed_rho) and subspace_in(Hin_hull, F4))
allok &= report("hull of the in-block seed is a proper subalgebra of Fix(E)", len(Hin_hull) < len(F4))
# hull is modular-invariant, so the omega-preserving projection onto it is a conditional expectation
PH = omega_expectation(Hin_hull, rho4)
Xr8 = rng.normal(size=(8, 8)) + 1j * rng.normal(size=(8, 8))
h1, h2 = Hin_hull[1], Hin_hull[-1]
allok &= report("E_H bimodular (Takesaki expectation onto the hull)", norm(PH(h1 @ Xr8 @ h2) - h1 @ PH(Xr8) @ h2) < 1e-8)
# E_H o E_t = E_H, with E_t = exp(t L4) as Schur multiplier in the eigenbasis of M
Dmat = np.zeros((8, 8))
for i in range(8):
    for j in range(8):
        Dmat[i, j] = 0.5 * (evals[i] - evals[j]) ** 2
Xe = evecs.conj().T @ Xr8 @ evecs
Xe_t = Xe * np.exp(-0.37 * Dmat)
Xt8 = evecs @ Xe_t @ evecs.conj().T
allok &= report("E_H o E_t = E_H on the hull of a stable seed", norm(PH(Xt8) - PH(Xr8)) < 1e-8)
join = hull(Pblocks + [seed_in], rho4, L4)
join2 = wstar(Hrec + Hin_hull, 8)
allok &= report("join law: hull(S u S') = hull(S) v hull(S')", len(join) == len(join2) and subspace_in(join, join2))

print("== 5. C-I example: fixed observable moved through a non-commutative algebra ==")
rho5 = np.kron(np.diag([0.8, 0.2]), np.eye(2) / 2)


def depol2(Xm):  # id (x) depolarisation generator on the second qubit, Heisenberg
    Xr_ = Xm.reshape(2, 2, 2, 2)
    out = np.zeros_like(Xr_)
    for a in range(2):
        for b in range(2):
            blk = Xr_[a, :, b, :]
            out[a, :, b, :] = np.trace(blk) / 2 * np.eye(2) - blk
    return out.reshape(4, 4)


H5 = hull([np.kron(X, I2)], rho5, depol2)
