"""Finite-dimensional checks for the candidate Foundation I.

Deterministic (fixed seeds).  Run:  python3 hull_finite.py > hull_finite.out

The hull of a seed S for a faithful density rho and a Heisenberg generator Lstar is the
smallest unital *-algebra containing S that is invariant under Ad rho^{is} (all s) and
exp(t Lstar) (all t >= 0).  In finite dimension a subspace is invariant under a one-parameter
group (semigroup) iff it is invariant under the generator, so the hull is the smallest
subspace containing S and 1 that is closed under products, adjoints, X -> [log rho, X]
and X -> Lstar(X).
"""
import numpy as np
from numpy.linalg import svd, norm, eigh
from scipy.linalg import expm, logm

np.set_printoptions(precision=6, suppress=True)
TOL = 1e-9


def basis(mats, tol=TOL):
    """Orthonormal basis (Hilbert-Schmidt) of the complex span of a list of matrices."""
    if not mats:
        return []
    n = mats[0].shape[0]
    M = np.array([m.reshape(-1) for m in mats]).T
    u, s, _ = svd(M, full_matrices=False)
    r = int((s > tol * max(1.0, s[0])).sum())
    return [u[:, i].reshape(n, n) for i in range(r)]


def hull(seed, rho, Lstar=None, maxit=50):
    n = rho.shape[0]
    K = logm(rho)
    B = basis([np.eye(n)] + list(seed))
    for _ in range(maxit):
        new = list(B)
        new += [b.conj().T for b in B]
        new += [K @ b - b @ K for b in B]
        if Lstar is not None:
            new += [Lstar(b) for b in B]
        new += [a @ b for a in B for b in B]
        B2 = basis(new)
        if len(B2) == len(B):
            return B2
        B = B2
    raise RuntimeError("no convergence")


def wstar(seed, n):
    """Unital *-algebra generated by seed (no flows)."""
    B = basis([np.eye(n)] + list(seed))
    while True:
        new = list(B) + [b.conj().T for b in B] + [a @ b for a in B for b in B]
        B2 = basis(new)
        if len(B2) == len(B):
            return B2
        B = B2


def contains(B, X, tol=1e-8):
    if not B:
        return norm(X) < tol
    M = np.array([b.reshape(-1) for b in B]).T
    c, *_ = np.linalg.lstsq(M, X.reshape(-1), rcond=None)
    return norm(M @ c - X.reshape(-1)) < tol * max(1, norm(X))


def subspace_in(B1, B2):
    return all(contains(B2, b) for b in B1)


def fixed_space(Lstar, n):
    """Kernel of Lstar on M_n."""
    E = [np.zeros((n, n), complex) for _ in range(n * n)]
    for k in range(n * n):
        E[k].reshape(-1)[k] = 1.0
    A = np.array([Lstar(e).reshape(-1) for e in E]).T
    u, s, vh = svd(A)
    null = [vh[i].conj().reshape(n, n) for i in range(n * n) if s[i] < 1e-10]
    return basis(null)


def is_star_algebra(B):
    return all(contains(B, b.conj().T) for b in B) and all(contains(B, a @ b) for a in B for b in B)


def modular_invariant(B, rho):
    K = logm(rho)
    return all(contains(B, K @ b - b @ K) for b in B)


def omega_expectation(B, rho):
    """Orthogonal projection onto span B in the GNS inner product <A,B> = Tr(rho A^* B)."""
    G = np.array([[np.trace(rho @ a.conj().T @ b) for b in B] for a in B])
    Ginv = np.linalg.inv(G)

    def P(X):
        v = np.array([np.trace(rho @ a.conj().T @ X) for a in B])
        c = Ginv @ v
        return sum(ci * b for ci, b in zip(c, B))
    return P


def dephasing(ops_rates):
    def L(X):
        return sum(g * (A @ X @ A - 0.5 * (A @ A @ X + X @ A @ A)) for A, g in ops_rates)
    return L


def report(name, ok):
    print(f"[{'PASS' if ok else 'FAIL'}] {name}")
    return ok


I2 = np.eye(2)
X = np.array([[0, 1], [1, 0]], complex)
Y = np.array([[0, -1j], [1j, 0]], complex)
Z = np.array([[1, 0], [0, -1]], complex)
P0 = np.array([[1, 0], [0, 0]], complex)


def kron(*ms):
    out = np.eye(1)
    for m in ms:
        out = np.kron(out, m)
    return out


allok = True
