L1 = dephasing([(Z, 1.0)])
rho = np.array([[0.7, 0.2], [0.2, 0.3]], complex)
stationary = norm(L1(rho)) < 1e-12  # L1 is self-dual (Schur multiplier), so Schroedinger = Heisenberg
H1 = hull([P0], rho, L1)
print("  omega stationary:", stationary, "  dim hull(P0) =", len(H1))
allok &= report("non-stationary qubit: hull of P0 is all of M_2 (dim 4)", (not stationary) and len(H1) == 4)
